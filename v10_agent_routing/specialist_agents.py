# SECTION 4: FILE SPECIALIST AGENT
# ==============================================================================
def file_agent(task):
    """
    Specialist agent tasked with performing file and directory actions.

    Parameters:
    -----------
    task : str
        The specific task description delegated to the file agent.

    Returns:
    --------
    str : The outcome of the file operation.
    """
    # System prompt enforcing strict JSON output and exposing only file tools
    system_prompt = """
You are the File Specialist Agent.

Your job is to handle file and folder related tasks.

Available tools:

1. list_files(path)
2. read_file(path)
3. create_folder(path)
4. create_file(path, content)

IMPORTANT:

Return ONLY JSON.

Do NOT use Markdown.
Do NOT use ```json.
Do NOT add explanations.

Examples:

Create a folder called Test:

{
    "tool": "create_folder",
    "arguments": {
        "path": "Test"
    }
}

Read a file:

{
    "tool": "read_file",
    "arguments": {
        "path": "test.txt"
    }
}

Create a file:

{
    "tool": "create_file",
    "arguments": {
        "path": "test.txt",
        "content": "Hello"
    }
}

List files:

{
    "tool": "list_files",
    "arguments": {
        "path": "."
    }
}

If no tool is appropriate:

{
    "tool": "none",
    "arguments": {}
}
"""

    # Assemble messages for the specialist
    messages = [
        {
            "role": "system",
            "content": system_prompt
        },
        {
            "role": "user",
            "content": task
        }
    ]

    # Call LLM
    response = call_ollama(messages)

    # Print raw response for debugging
    print("\nRAW FILE AGENT RESPONSE:")
    print(response)

    # Parse JSON tool selection
    decision = parse_tool_response(response)

    # Validate decision dictionary
    if decision is None:
        return "File Agent returned an invalid response."

    # Extract chosen tool name and arguments dictionary
    tool = decision.get("tool")
    arguments = decision.get("arguments", {})

    # Execute tool matching the agent's decision
    if tool == "list_files":
        return list_files(**arguments)
    elif tool == "read_file":
        return read_file(**arguments)
    elif tool == "create_folder":
        return create_folder(**arguments)
    elif tool == "create_file":
        return create_file(**arguments)
    else:
        return "File Agent could not determine a valid tool."


