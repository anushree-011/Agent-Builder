# Stores Ollama Cloud connection parameters shared across all specialist agents
OLLAMA_API_KEY = None       # API token for authenticating calls
OLLAMA_BASE_URL = None      # Base URL endpoint for Ollama Cloud
MODEL_NAME = None           # Model name (e.g., gemma4:31b)


def configure_ollama(api_key, base_url, model_name):
    """
    Configures connection settings for all specialist agents.

    Parameters:
    -----------
    api_key : str
        The bearer authentication key required for API access.
    base_url : str
        The root API endpoint URL for Ollama Cloud service.
    model_name : str
        The identifier of the LLM to use for specialist inference.
    """
    # Declare globals to modify module-level state
    global OLLAMA_API_KEY
    global OLLAMA_BASE_URL
    global MODEL_NAME

    # Assign values from function parameters
    OLLAMA_API_KEY = api_key
    OLLAMA_BASE_URL = base_url
    MODEL_NAME = model_name


# ==============================================================================
# SECTION 2: LLM API INVOCATION
# ==============================================================================
def call_ollama(messages):
    """
    Dispatches chat messages to the Ollama Cloud chat endpoint.

    Parameters:
    -----------
    messages : list of dict
        Message sequence [{"role": "system"|"user", "content": "..."}].

    Returns:
    --------
    str : Raw text response produced by the specialist model.
    """
    # Build complete chat endpoint URL
    url = f"{OLLAMA_BASE_URL}/chat"

    # Set up HTTP authorization and content headers
    headers = {
        "Authorization": f"Bearer {OLLAMA_API_KEY}",
        "Content-Type": "application/json"
    }

    # Prepare HTTP payload
    payload = {
        "model": MODEL_NAME,
        "messages": messages,
        "stream": False  # Synchronous response
    }

    # Send POST request with 120-second timeout
    response = requests.post(
        url,
        headers=headers,
        json=payload,
        timeout=120
    )

    # Raise an exception if an HTTP error status code was returned
    response.raise_for_status()

    # Extract JSON body
    data = response.json()

    # Return text content of the message
    return data["message"]["content"]


# ==============================================================================
# SECTION 3: STRUCTURED TOOL RESPONSE PARSER
# ==============================================================================
def parse_tool_response(response):
    """
    Parses a specialist agent's text output into a dictionary specifying tool and arguments.

    Handles cases where models output raw JSON or surround JSON with markdown fences:
    ```json
    {"tool": "read_file", "arguments": {"path": "test.txt"}}
    ```

    Parameters:
    -----------
    response : str
        Raw string output from the LLM.

    Returns:
    --------
    dict or None : Parsed JSON dictionary if valid, otherwise None.
    """
    # Strip any leading and trailing whitespace
    response = response.strip()

    # Strip opening markdown code block identifier
    if response.startswith("```json"):
        response = response[7:]
    elif response.startswith("```"):
        response = response[3:]

    # Strip closing markdown code block delimiter
    if response.endswith("```"):
        response = response[:-3]

    # Re-strip clean content
    response = response.strip()

    # Attempt standard JSON decoding
    try:
        return json.loads(response)
    except json.JSONDecodeError:
        # Print diagnostic output if response fails parsing
        print("\nSPECIALIST RETURNED INVALID JSON:")
        print(response)
        return None


