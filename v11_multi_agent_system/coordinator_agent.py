"""
==============================================================================
V11 - MULTI-AGENT SYSTEM: COORDINATOR AGENT MODULE
==============================================================================
Concept & Architecture:
This module implements the "Coordinator Agent" (also known as the Orchestrator)
in a Multi-Agent System (MAS).

Unlike a simple Router (v10) which merely picks one agent for a single query,
the Coordinator handles complex multi-step workflows requiring teamwork:
1. Task Decomposition: Breaks a complex user prompt into an ordered sequence of subtasks.
2. Agent Assignment: Assigns each subtask to the appropriate specialist agent.
3. Shared State Execution: Runs each step sequentially, passing shared state so downstream
   agents can access information produced by upstream agents.
4. Final Synthesis: Synthesizes a cohesive final summary of all results for the user.

Key Topics:
- Multi-Agent Orchestration & Planning.
- Inter-Agent Communication via Shared State.
- Error Isolation & Sequential Dependency Management.
- Final Output Synthesis.
==============================================================================
"""

# Import the standard JSON library to serialize and deserialize structured planning payloads
import json

# Import the requests library to send HTTP POST calls to Ollama Cloud
import requests

# Import the SharedState class which serves as the blackboard / common memory for all agents
from shared_state import SharedState

# Import the dictionary of specialist agent handlers from the agents module
from agents import SPECIALIST_AGENTS


# ==============================================================================
# SECTION 1: GLOBAL CONFIGURATION STATE
# ==============================================================================
# Stores Ollama Cloud connection parameters for the coordinator agent
OLLAMA_API_KEY = None       # API authentication token for Ollama Cloud
OLLAMA_BASE_URL = None      # Base URL endpoint for Ollama Cloud (e.g. https://ollama.com/api)
MODEL_NAME = None           # Identifier of the LLM model (e.g. gemma4:31b)


def configure_coordinator(api_key, base_url, model_name):
    """
    Sets global API credentials and model configuration for the Coordinator Agent.

    Parameters:
    -----------
    api_key : str
        The bearer authentication key required for API access.
    base_url : str
        The root API endpoint URL for Ollama Cloud service.
    model_name : str
        The identifier of the LLM to use for planning and synthesis.
    """
    # Use global keyword to modify module-level variables
    global OLLAMA_API_KEY
    global OLLAMA_BASE_URL
    global MODEL_NAME

    # Assign configuration parameters to module globals
    OLLAMA_API_KEY = api_key
    OLLAMA_BASE_URL = base_url
    MODEL_NAME = model_name


# ==============================================================================
# SECTION 2: LLM API INVOCATION
# ==============================================================================
def call_ollama(messages):
    """
    Sends chat messages to Ollama Cloud and extracts the model's textual response.

    Parameters:
    -----------
    messages : list of dict
        A list of chat messages formatted as [{"role": "system"|"user", "content": "..."}].

    Returns:
    --------
    str : Text response generated by the LLM.
    """
    # Target endpoint URL for chat completions
    url = f"{OLLAMA_BASE_URL}/chat"

    # Define headers with Bearer authentication and JSON content type
    headers = {
        "Authorization": f"Bearer {OLLAMA_API_KEY}",
        "Content-Type": "application/json"
    }

    # Prepare request payload
    payload = {
        "model": MODEL_NAME,
        "messages": messages,
        "stream": False  # Synchronous single-shot response
    }

    # Execute HTTP POST request with 120s timeout
    response = requests.post(
        url,
        headers=headers,
        json=payload,
        timeout=120
    )

    # Raise an exception if an HTTP error code was returned
    response.raise_for_status()

    # Parse response body as JSON
    data = response.json()

    # Extract and return the assistant's message text
    return data["message"]["content"]


# ==============================================================================
# SECTION 3: STRUCTURED JSON PARSER
# ==============================================================================
def parse_json_response(response):
    """
    Cleans and parses JSON output from LLM responses, stripping code blocks if present.

    Parameters:
    -----------
    response : str
        The raw string response returned by the LLM.

    Returns:
    --------
    dict or list or None : Parsed JSON object if valid, otherwise None.
    """
    # Strip leading and trailing whitespace
    response = response.strip()

    # Remove opening markdown code fence if present
    if response.startswith("```json"):
        response = response[7:]
    elif response.startswith("```"):
        response = response[3:]

    # Remove closing markdown code fence if present
    if response.endswith("```"):
        response = response[:-3]

    # Re-trim whitespace
    response = response.strip()

    # Attempt to parse into a Python data structure
    try:
        return json.loads(response)
    except json.JSONDecodeError:
        # Print diagnostic error information
        print()
        print("Invalid Coordinator JSON:")
        print(response)
        return None


# ==============================================================================
# SECTION 4: TASK DECOMPOSITION & PLANNING
# ==============================================================================
def create_plan(task):
    """
    Prompts the LLM to analyze the user's high-level request, decompose it into
    a sequential list of steps, and assign each step to a specific specialist agent.

    Parameters:
    -----------
    task : str
        The multi-step or complex natural language request from the user.

    Returns:
    --------
    dict or None : A dictionary containing the list of planned steps:
                   {"steps": [{"agent": "...", "task": "..."}, ...]}
    """
    # Define detailed instructions and schema rules for multi-step planning
    system_prompt = """
You are the Coordinator Agent.

Your job is to break a user task into steps
and decide which specialist agent should perform
each step.

Available agents:

FILE_AGENT
- Files and folders

MEMORY_AGENT
- Memory operations

CALCULATOR_AGENT
- Mathematical calculations

IMPORTANT:

A task can contain multiple steps.

Return ONLY JSON.

Format:

{
    "steps": [
        {
            "agent": "FILE_AGENT",
            "task": "Create a folder called V11_Project"
        },
        {
            "agent": "FILE_AGENT",
            "task": "Create README.md inside V11_Project"
        },
        {
            "agent": "MEMORY_AGENT",
            "task": "Remember that V11_Project was created"
        }
    ]
}

Rules:

1. Use only the available agents.
2. Put steps in the correct order.
3. If one step depends on another, put the dependency first.
4. Keep each task clear and specific.
5. Return only JSON.
"""

    # Assemble messages payload
    messages = [
        {
            "role": "system",
            "content": system_prompt
        },
        {
            "role": "user",
            "content": task
        }
    ]

    # Call LLM to produce execution plan
    response = call_ollama(messages)

    # Print raw plan response for full transparency
    print()
    print("RAW COORDINATOR PLAN:")
    print(response)

    # Clean and parse plan JSON
    return parse_json_response(response)


# ==============================================================================
# SECTION 5: PLAN EXECUTION LOOP
# ==============================================================================
def execute_plan(plan, shared_state):
    """
    Iterates through each planned step, invokes the designated specialist agent,
    records results into the SharedState object, and displays real-time progress.

    Parameters:
    -----------
    plan : dict
        The execution plan containing the 'steps' list.
    shared_state : SharedState
        The shared state object storing execution history and outputs.

    Returns:
    --------
    str : Status message indicating plan completion.
    """
    # Validate that plan is not None
    if not plan:
        return "Coordinator could not create a valid plan."

    # Extract list of steps from plan dictionary
    steps = plan.get("steps", [])

    # Guard against empty plan lists
    if not steps:
        return "Coordinator created an empty plan."

    # Display visual banner for the execution plan
    print()
    print("=" * 60)
    print("EXECUTION PLAN")
    print("=" * 60)

    # Print each planned step before starting execution
    for index, step in enumerate(steps, start=1):
        print()
        print(f"Step {index}")
        print(f"Agent: {step.get('agent')}")
        print(f"Task: {step.get('task')}")

    # ==========================================================================
    # SEQUENTIAL STEP EXECUTION
    # ==========================================================================
    for index, step in enumerate(steps, start=1):
        # Extract target specialist name and subtask string
        agent_name = step.get("agent")
        agent_task = step.get("task")

        print()
        print("=" * 60)
        print(f"EXECUTING STEP {index}")
        print("=" * 60)

        # Check if the requested agent is registered
        if agent_name not in SPECIALIST_AGENTS:
            result = f"Unknown agent: {agent_name}"
            # Record failure in shared state and proceed to next step
            shared_state.add_result(agent_name, result)
            continue

        # Look up specialist function from the registry
        specialist = SPECIALIST_AGENTS[agent_name]

        # Safely execute specialist, passing both subtask and shared_state
        try:
            result = specialist(agent_task, shared_state)
        except Exception as error:
            # Handle unexpected runtime errors during specialist execution
            result = f"Agent execution error: {error}"

        # Print the immediate result produced by the specialist
        print()
        print(f"RESULT FROM {agent_name}:")
        print(result)

        # ----------------------------------------------------------------------
        # Commit result into shared state blackboard
        # ----------------------------------------------------------------------
        shared_state.add_result(agent_name, result)

        # ----------------------------------------------------------------------
        # Display updated shared state snapshot
        # ----------------------------------------------------------------------
        shared_state.display()

    return "Plan execution completed."


# ==============================================================================
# SECTION 6: FINAL SYNTHESIS & REPORTING
# ==============================================================================
def create_final_summary(task, shared_state):
    """
    Prompts the LLM to review the original task and the accumulated results from
    all specialist agents in shared state, creating a unified summary response.

    Parameters:
    -----------
    task : str
        The initial request asked by the user.
    shared_state : SharedState
        The shared state containing all executed agent outputs.

    Returns:
    --------
    str : A coherent synthesized response for the user.
    """
    # Retrieve all results accumulated during plan execution
    results = shared_state.get_results()

    # Build prompt giving full context of all agent outputs
    prompt = f"""
You are the Coordinator Agent.

The user originally requested:

{task}

The specialist agents completed these steps:

{results}

Create a short final response for the user.

Explain:

1. What was completed.
2. Which agents participated.
3. Important results.

Do not invent anything.
Only use the provided results.
"""

    # Assemble messages
    messages = [
        {
            "role": "system",
            "content": "You summarize multi-agent work."
        },
        {
            "role": "user",
            "content": prompt
        }
    ]

    # Call LLM to generate summary
    return call_ollama(messages)


# ==============================================================================
# SECTION 7: COORDINATOR PIPELINE RUNNER
# ==============================================================================
def run_coordinator(task):
    """
    Main entry point for multi-agent coordination.
    1. Instantiates a new SharedState container.
    2. Calls create_plan() to generate multi-step tasks.
    3. Executes the plan step-by-step with execute_plan().
    4. Generates a final synthesis with create_final_summary().

    Parameters:
    -----------
    task : str
        The high-level user request.

    Returns:
    --------
    str : The final synthesized report.
    """
    # Initialize shared state for this task
    shared_state = SharedState(task)

    print()
    print("=" * 60)
    print("V11 MULTI-AGENT SYSTEM")
    print("=" * 60)

    # STEP 1: Decompose task into multi-agent plan
    plan = create_plan(task)

    # STEP 2: Execute each step with specialists
    execute_plan(plan, shared_state)

    # STEP 3: Synthesize final summary
    print()
    print("=" * 60)
    print("CREATING FINAL SUMMARY")
    print("=" * 60)

    final_answer = create_final_summary(task, shared_state)

    return final_answer